#!/usr/bin/env python3
"""Generate src/dxcorpus.c (the 6.89 built-in cycle text as C89 data) from BMDC.BIN.

Usage: gen_corpus_c.py [BMDC.BIN] [-o ../src/dxcorpus.c]

Every block of the text area becomes one string literal, empty blocks included
(they end a routine; execution falls through them like the firmware does).
Tables A and B become block indices. All table entries must point at block
starts, which holds for 6.89; the script stops if one does not.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from extract_corpus import TABLES, blocks, read_tables  # noqa: E402


def cstr(s):
    out = []
    for ch in s:
        if ch in '\\"':
            out.append("\\" + ch)
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.append("\\%03o" % ord(ch))
    return '"' + "".join(out) + '"'


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser()
    ap.add_argument("image", nargs="?", default=os.path.join(here, "..", "..", "BMDC.BIN"))
    ap.add_argument("-o", "--output", default=os.path.join(here, "..", "src", "dxcorpus.c"))
    args = ap.parse_args()
    img = open(args.image, "rb").read()
    blks = list(blocks(img))
    index = {off: i for i, (off, _) in enumerate(blks)}
    tabs = read_tables(img)
    lines = [
        "/* dxcorpus.c - GENERATED by tools/gen_corpus_c.py from BMDC.BIN 6.89.  Do not edit.",
        " *",
        " * The firmware's built-in canned-cycle programs (file offsets 0x26926-0x27b2e) as",
        " * one string per NUL-terminated block, and the two entry tables:",
        " *   table A (0x26852): =%n calls (entry n+9), cycle bodies and drivers",
        " *   table B (0x268f6): %n jumps",
        " */",
        '#include "dxsim.h"',
        "",
        "const int dxcorpn = %d;" % len(blks),
        "",
        "const char *const dxcorptx[] = {",
    ]
    for off, text in blks:
        lines.append("    %s, /* %05x */" % (cstr(text), off))
    lines.append("    0\n};\n")
    lines.append("const long dxcorpof[] = {")
    for i in range(0, len(blks), 8):
        lines.append("    " + ", ".join("0x%05lxL" % off for off, _ in blks[i:i + 8]) + ",")
    lines.append("    0L\n};\n")
    for name, base, count in TABLES:
        idx = []
        for p in tabs[name]:
            if p not in index:
                sys.exit("table %s entry %05x is not a block start" % (name, p))
            idx.append(index[p])
        lines.append("const int dxcorpt%s[%d] = {" % (name.lower(), count))
        for i in range(0, count, 10):
            lines.append("    " + ", ".join(str(x) for x in idx[i:i + 10]) + ",")
        lines.append("};\n")
    open(args.output, "w").write("\n".join(lines))
    print("wrote %s: %d blocks" % (args.output, len(blks)))


if __name__ == "__main__":
    main()
